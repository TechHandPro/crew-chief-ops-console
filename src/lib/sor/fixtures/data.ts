export function toDocumentSummary(doc: DocumentDetail): DocumentSummary {
  const meta = DOCUMENT_META[doc.id];
  const preview = doc.content.replace(/\s+/g, " ").trim();
  return {
    id: doc.id,
    title: doc.title,
    category: doc.category,
    organizationId: doc.organizationId,
    bodyPreview: preview.length > 220 ? `${preview.slice(0, 220)}...` : preview,
    ...meta,
  };
}

